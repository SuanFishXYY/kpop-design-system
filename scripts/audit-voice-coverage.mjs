// scripts/audit-voice-coverage.mjs
// v3.6.1 · Standalone voice/persona coverage audit.
//
// Derives a persona and sample lines for every idol and group, then reports
// coverage gaps (default tones, empty levers/habits, duplicate lines, etc.).
// No external LLM calls.

import { loadIdols } from "../engine/council-assembly.mjs";
import { loadGroups } from "../engine/relations.mjs";
import { derivePersona } from "../engine/voice-persona.mjs";
import { speakInCharacter } from "../engine/speak.mjs";
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const DOCS_DIR = join(__dirname, "..", "docs");

const DEFAULT_TONE = "专业、冷静、以设计证据说话";
const BRIEF = "landing page";
const STANCES = ["agree", "reserve", "dissent"];

function normalizeName(member) {
  return member.type === "group" ? `group:${member.slug}` : member.slug;
}

function auditMember(member) {
  const persona = derivePersona(member, BRIEF, { tension: 1 });
  const lines = STANCES.map(stance => speakInCharacter(persona, { topic: BRIEF, stance }));
  return { member, persona, lines };
}

function main() {
  const idols = loadIdols().map(i => ({ ...i, type: "idol" }));
  const groups = loadGroups().filter(g => g.slug).map(g => ({ ...g, type: "group" }));
  const all = [...idols, ...groups];

  const results = all.map(auditMember);

  const anomalies = {
    defaultTone: [],
    emptyLevers: [],
    emptyHabits: [],
    emptySignature: [],
    emptyVoiceIdentity: [],
    emptyHardVeto: [],
  };

  const allLines = [];
  for (const r of results) {
    const key = normalizeName(r.member);
    const p = r.persona;
    if (p.tone === DEFAULT_TONE) anomalies.defaultTone.push(key);
    if (!p.negotiation_levers?.length) anomalies.emptyLevers.push(key);
    if (!p.speech_habits?.length) anomalies.emptyHabits.push(key);
    if (!p.signature_phrase) anomalies.emptySignature.push(key);
    if (!p.voice_identity) anomalies.emptyVoiceIdentity.push(key);
    if (!p.hard_veto?.length) anomalies.emptyHardVeto.push(key);
    allLines.push(...r.lines.map(line => ({ key, line })));
  }

  const uniqueLines = new Set(allLines.map(x => x.line));
  const duplicateLines = [];
  const seen = new Map();
  for (const { key, line } of allLines) {
    if (seen.has(line)) {
      duplicateLines.push({ line, keys: [seen.get(line), key] });
    } else {
      seen.set(line, key);
    }
  }

  const totalMembers = all.length;
  const totalLines = allLines.length;

  const report = [`# Voice & Persona Coverage Audit

Generated by \`scripts/audit-voice-coverage.mjs\`.

## Summary

| Metric | Value |
|--------|-------|
| Idols audited | ${idols.length} |
| Groups audited | ${groups.length} |
| Total members | ${totalMembers} |
| Sample lines generated | ${totalLines} |
| Unique lines | ${uniqueLines.size} |
| Uniqueness ratio | ${((uniqueLines.size / totalLines) * 100).toFixed(1)}% |
| Members with default tone | ${anomalies.defaultTone.length} |
| Members with empty levers | ${anomalies.emptyLevers.length} |
| Members with empty habits | ${anomalies.emptyHabits.length} |
| Members with empty signature | ${anomalies.emptySignature.length} |
| Members with empty voice identity | ${anomalies.emptyVoiceIdentity.length} |
| Members with empty hard veto | ${anomalies.emptyHardVeto.length} |
| Duplicate line collisions | ${duplicateLines.length} |
`];

  function section(title, items) {
    if (!items.length) return "";
    return `\n## ${title}\n\n${items.map(x => `- ${x}`).join("\n")}\n`;
  }

  report.push(section("Default-tone members", anomalies.defaultTone));
  report.push(section("Empty-lever members", anomalies.emptyLevers));
  report.push(section("Empty-habit members", anomalies.emptyHabits));
  report.push(section("Empty-signature members", anomalies.emptySignature));
  report.push(section("Empty-voice-identity members", anomalies.emptyVoiceIdentity));
  report.push(section("Empty-hard-veto members", anomalies.emptyHardVeto));

  if (duplicateLines.length) {
    report.push(`\n## Duplicate line samples\n`);
    for (const d of duplicateLines.slice(0, 20)) {
      report.push(`- ${d.keys.join(" / ")}: ${d.line.slice(0, 120)}...`);
    }
  }

  // Sample lines: 6 diverse members across tones.
  const sampleKeys = new Set();
  const samples = [];
  for (const r of results) {
    if (samples.length >= 6) break;
    const key = normalizeName(r.member);
    if (!sampleKeys.has(r.persona.tone)) {
      sampleKeys.add(r.persona.tone);
      samples.push(r);
    }
  }

  report.push(`\n## Sample lines across tones\n`);
  for (const s of samples) {
    report.push(`\n### ${s.member.name} (${s.persona.tone})\n`);
    for (let i = 0; i < STANCES.length; i++) {
      report.push(`- **${STANCES[i]}**: ${s.lines[i]}`);
    }
  }

  const output = report.join("");
  writeFileSync(join(DOCS_DIR, "VOICE-COVERAGE-AUDIT.md"), output, "utf-8");
  console.log(`Wrote docs/VOICE-COVERAGE-AUDIT.md`);
  console.log(`Members: ${totalMembers}, unique lines: ${uniqueLines.size}/${totalLines} (${((uniqueLines.size / totalLines) * 100).toFixed(1)}%), anomalies: ${Object.values(anomalies).flat().length}`);
  if (Object.values(anomalies).some(arr => arr.length)) {
    process.exitCode = 1;
  }
}

main();
